--- Maximum length of a generated EPUB filename, in bytes.
local MAX_FILENAME_LENGTH = 120

--- Number of catalog entries requested per page.
local function pageSize()
    local size = tonumber(config.page_size) or 40
    if size < 1 then size = 40 end
    if size > 100 then size = 100 end
    return size
end

