--- Opens the search dialog.
function LightHouse:showSearchDialog()
    local dialog
    dialog = squareWidget(InputDialog, {
        title = _("Search the LightHouse library"),
        input = "",
        input_hint = _("Title, author or series"),
        buttons = {
            {
                {
                    text = _("Cancel"),
                    id = "close",
                    callback = function() UIManager:close(dialog) end,
                },
                {
                    text = _("Search"),
                    is_enter_default = true,
                    callback = function()
                        local query = dialog:getInputText()
                        UIManager:close(dialog)
                        -- `getInputText` is a widget API, and a widget that
                        -- returned something other than a string would make
                        -- `:gsub` raise instead of searching.
                        query = Status.str(query):gsub("^%s+", ""):gsub("%s+$", "")
                        if query == "" then
                            self:openLibrary{ mode = "books", page = 1, query = "" }
                        else
                            self:openLibrary{ mode = "books", page = 1, query = query }
                        end
                    end,
                },
            },
        },
    })
    UIManager:show(dialog)
    dialog:onShowKeyboard()
end

--- Builds one row of the currently-reading shelf.
-- The per-session half of `showReading`, named so this crash class is testable.
-- This is where `T(_("File: %1"), session.filename)` lives - the line the device
-- died on - and where a field the server sent as `null` used to reach `gsub`.
-- Every session field is read through `Status.str` first, so the guard clauses
-- below test real strings and `T()` only ever sees strings.
-- @tparam table session normalized KOSync session
-- @tparam table[opt] layout result of `Ui.layout`
-- @treturn table Menu item
function LightHouse:buildReadingItem(session, layout)
    if type(session) ~= "table" then session = {} end
    local title = Status.str(session.title)
    if title == "" then title = _("Untitled") end
    local device = Status.str(session.device)
    local filename = Status.str(session.filename)
    local book_id = Status.num(session.book_id)
    if book_id then book_id = math.floor(book_id) end

    local details = {}
    -- A session can point at a book this device no longer has (deleted after it
    -- was read), so the file itself decides which action the row offers.
    local local_book_path = Status.str(session.book_path)
    local has_local_file = local_book_path ~= "" and Sidecar.bookExists(local_book_path)
    if book_id then
        local session_for_download = session
        details[#details + 1] = {
            text = _("Download EPUB"),
            bold = true,
            callback = function() self:downloadBookId(session_for_download) end,
        }
    elseif has_local_file then
        -- A book this device already has (and the server has no Calibre id
        -- for) is opened from disk instead of being offered for download.
        details[#details + 1] = {
            text = _("Open book"),
            bold = true,
            callback = function() self:openBookFile(local_book_path) end,
        }
    elseif local_book_path ~= "" then
        -- The sidecar outlived the book: the row stays (its progress and
        -- highlights are real) but must not pretend it can open a gone file.
        details[#details + 1] = {
            text = _("Book file is missing from this device"),
            enabled = false,
            callback = function() end,
        }
    else
        details[#details + 1] = {
            text = _("No matching book in the library"),
            enabled = false,
            callback = function() end,
        }
    end
    details[#details + 1] = {
        text = T(_("Progress: %1"), Status.progressBar(Status.num(session.percentage))),
        callback = function() end,
    }
    -- Where the number came from. A local sidecar value replaces the server's
    -- for this book (see `localRecordFor`), and the row says so.
    if Status.str(session.progress_source) == "device" then
        details[#details + 1] = {
            text = _("Progress read from this device"),
            select_enabled = false,
            callback = function() end,
        }
    end
    local local_record = type(session.local_record) == "table" and session.local_record or nil
    if local_record and (Status.num(local_record.annotation_count) or 0) > 0 then
        details[#details + 1] = {
            text = T(_("Highlights: %1"), Status.num(local_record.annotation_count)),
            callback = function() self:showHighlights() end,
        }
    end
    if device ~= "" then
        details[#details + 1] = {
            text = T(_("Device: %1"), device),
            callback = function() end,
        }
    end
    if filename ~= "" then
        details[#details + 1] = {
            text = T(_("File: %1"), filename),
            callback = function() end,
        }
    end

    return self:buildRow{
        layout = layout,
        cover_entry = book_id and { book_id = book_id } or nil,
        primary = title,
        secondary = Ui.secondaryLine{
            authors = Status.str(session.authors),
            extra = device ~= "" and device or nil,
            fallback = _("Unknown"),
        },
        glance = self:progressGlance(session),
        details = details,
    }
end

--- Shows every active KOSync session, newest first, with this device's own
-- books and progress in front of the server's copy.
--
-- Offline-first: the shelf is built from the device's sidecar files, so it opens
-- with no connection at all. The server's sessions are merged on top when they
-- are reachable, and only the books this device has never seen depend on them.
function LightHouse:showReading()
    local local_records = self:withLocalScan(_("Reading books on this device…"), function()
        return self:localRecords()
    end)
    local configured = Client.isConfigured(config)
    local online = NetworkMgr:isOnline()

    if #local_records == 0 then
        if not configured then
            self:showProblem{
                title = _("Currently reading"),
                headline = errorHeadline("not_configured"),
                detail = describeError("not_configured"),
                actions = { connectionAction(self) },
            }
            return
        end
        if not online then
            NetworkMgr:willRerunWhenOnline(function() self:showReading() end)
            return
        end
    end

    local sessions, err
    if configured and online then
        sessions, err = self:withSpinner(_("Loading reading progress…"), function()
            return self:fetchSessions()
        end)
    end

    local shelf = self:mergeReadingShelf(sessions, local_records)
    if #shelf == 0 then
        if not sessions then
            -- No server sessions and nothing local: a failed request is what
            -- happened, so say that instead of claiming nothing is in progress.
            self:showProblem{
                title = _("Currently reading"),
                headline = errorHeadline(err),
                detail = describeError(err),
                actions = {
                    retryAction(_("Try again"), function() self:showReading() end),
                    connectionAction(self),
                },
            }
        else
            self:showProblem{
                title = _("Currently reading"),
                headline = _("Nothing in progress yet"),
                detail = _("Open a book in KOReader with progress sync on, then come back."),
                actions = {
                    retryAction(_("Refresh"), function() self:showReading() end),
                    { text = _("Browse library"), callback = function() self:openLibrary{ mode = "books", page = 1 } end },
                },
            }
        end
        return
    end

    local with_covers = self:coversEnabled()
    if with_covers then
        -- The progress endpoint carries the Calibre id, so the shelf can show
        -- covers without asking the server for anything else. A book only this
        -- device has read has no id, so it simply has no cover here.
        local cover_entries = {}
        for session_index = 1, #shelf do
            local session = shelf[session_index]
            local book_id = Status.num(session.book_id)
            if book_id then
                book_id = math.floor(book_id)
                cover_entries[#cover_entries + 1] = {
                    book_id = book_id,
                    thumbnail_href = Client.buildUrl(config, string.format(
                        "/api/books/%d/cover?w=%d",
                        book_id,
                        Ui.tokens.cover_width_px
                    )),
                }
            end
        end
        local now = os.time()
        local pending = 0
        for entry_index = 1, #cover_entries do
            if coverNeedsFetch(cover_entries[entry_index], now) then
                pending = pending + 1
            end
        end
        if pending > 0 then
            self:withSpinner(_("Loading covers…"), function()
                self:prefetchCovers(cover_entries)
                return true
            end)
        end
    end

    local layout = self:layoutFor(with_covers)
    local items = {}
    -- The server did not answer but this device did: say which data is on
    -- screen instead of presenting a partial shelf as the whole truth. It is a
    -- note row, not an action, and every book row below it still works.
    if not sessions and err ~= nil then
        items[#items + 1] = self:buildRow{
            primary = _("This device only - the server could not be reached."),
            select_enabled = false,
        }
    end
    -- `session_index`, not `_`: `_` is gettext in this file (see the note by
    -- its require), so using it as a throwaway aborted the whole process on
    -- the device the moment a row called `_("…")`.
    -- Every row is built through `buildSafeRow`: a session this shelf cannot
    -- render costs its own row, not the remaining rows and not the process.
    for session_index = 1, #shelf do
        local session = shelf[session_index]
        items[#items + 1] = self:buildSafeRow(function()
            return self:buildReadingItem(session, layout)
        end)
    end

    self:showMenu(_("Currently reading"), items, { covers = with_covers, layout = layout })
end

--- Shows this device's highlights, newest first, grouped by book.
--
-- Offline-first and strictly read-only: the rows come from the sidecar files
-- beside the books on this device, read once when the view opens (`localRecords`
-- caches that scan for the session), with no network call and no polling.
function LightHouse:showHighlights()
    local groups = Sidecar.highlightGroups(self:withLocalScan(_("Reading this device's highlights…"), function()
        return self:localRecords()
    end))
    if #groups == 0 then
        self:showProblem{
            title = _("Highlights"),
            headline = _("No highlights on this device yet"),
            detail = _("Highlight a passage in KOReader and it appears here, read from this device - no connection needed."),
            actions = {
                retryAction(_("Refresh"), function()
                    self:localRecords(true)
                    self:showHighlights()
                end),
                { text = _("Browse library"), callback = function() self:openLibrary{ mode = "books", page = 1 } end },
            },
        }
        return
    end

    local items = {}
    for group_index = 1, #groups do
        local group = groups[group_index]
        local annotations = {}
        for annotation_index = 1, #group.annotations do
            local annotation = group.annotations[annotation_index]
            -- One unrenderable highlight costs its own row, never the view.
            annotations[#annotations + 1] = self:buildSafeRow(function()
                return self:buildHighlightItem(group, annotation)
            end)
        end
        items[#items + 1] = self:buildSafeRow(function()
            return self:buildHighlightGroupItem(group, annotations)
        end)
    end

    self:showMenu(_("Highlights on this device"), items, { covers = false })
end

--- One book heading in the highlights view: title, author, highlight count.
-- @tparam table group entry from `Sidecar.highlightGroups`
-- @tparam table annotations prebuilt highlight rows for this book
-- @treturn table Menu item
function LightHouse:buildHighlightGroupItem(group, annotations)
    local title = Status.str(group and group.title)
    if title == "" then title = _("Untitled") end
    return self:buildRow{
        primary = title,
        secondary = Status.str(group and group.authors, _("Unknown")),
        glance = T(_("Highlights: %1"), Status.num(group and group.annotation_count)),
        details = annotations,
    }
end

--- One highlight row: the quote leads, its position and style follow.
--
-- Colour and style are OPTIONAL - the verified device book's annotations carried
-- neither `color` nor `drawer` - so an absent style costs nothing on the row
-- instead of a placeholder that would imply something is missing.
-- @tparam table group book this highlight belongs to
-- @tparam table annotation normalized annotation
-- @treturn table Menu item
function LightHouse:buildHighlightItem(group, annotation)
    local text = Sidecar.annotationText(annotation)
    -- A menu row is one line, so the quote is flattened here rather than left
    -- to KOReader's own newline handling.
    if text == "" then text = _("Untitled note") end

    local glance_parts = {}
    local page = Sidecar.annotationPage(annotation)
    if page then glance_parts[#glance_parts + 1] = T(_("p. %1"), page) end
    local style = Sidecar.styleLabel(annotation)
    if style ~= "" then glance_parts[#glance_parts + 1] = style end

    return self:buildRow{
        primary = text,
        secondary = Status.str(annotation and annotation.chapter),
        glance = Ui.join(glance_parts),
        callback = function() self:openHighlight(group, annotation) end,
    }
end

--- Opens the book behind one highlight.
--
-- Strictly read-only: no sidecar is written and no progress is sent anywhere -
-- the write surface of this plugin is unchanged. The page jump goes through the
-- reader's own navigation module inside `pcall`, so a KOReader build without
-- that hook opens the book at its last position instead of raising. When the
-- book file itself is gone, the note text is shown instead - it is the only
-- thing left to offer, and it is what the reader tapped for.
-- @tparam table group book this highlight belongs to
-- @tparam table annotation normalized annotation
function LightHouse:openHighlight(group, annotation)
    local book_path = Status.str(group and group.book_path)
    if book_path == "" or not Sidecar.bookExists(book_path) then
        self:showHighlightNote(group, annotation)
        return
    end
    local opened = self:openBookFile(book_path)
    if not opened then
        self:showHighlightNote(group, annotation)
        return
    end
    local page = Sidecar.annotationPage(annotation)
    if page then self:jumpToPage(page) end
end

--- Opens one book that is already on this device.
-- Fully guarded: a book KOReader refuses to open is reported in the log and
-- returns false, instead of raising out of a menu callback.
-- @string book_path
-- @treturn boolean opened
function LightHouse:openBookFile(book_path)
    local path = Status.str(book_path)
    if path == "" then return false end
    local opened, raise = pcall(function()
        local ReaderUI = require("apps/reader/readerui")
        ReaderUI:showReader(path)
    end)
    if not opened then
        logger.warn("LightHouse: opening", path, "raised:", tostring(raise))
        return false
    end
    return true
end

--- Jumps the freshly opened book to a highlight's page, best effort.
-- The reader instance is not created synchronously, so the jump is deferred a
-- tick and every hop is `pcall`ed: a build without `rolling`/`paging`
-- navigation, or a page past the end, must cost the jump and not the process.
-- @number page 1-based page number
-- @treturn boolean scheduled
function LightHouse:jumpToPage(page)
    local target = Status.num(page)
    if not target then return false end
    target = math.floor(target)
    if target < 1 then return false end
    local scheduled, raise = pcall(function()
        UIManager:nextTick(function()
            local jumped, jump_error = pcall(function()
                local ReaderUI = require("apps/reader/readerui")
                local reader = ReaderUI.instance
                if type(reader) ~= "table" then return end
                local navigation = reader.rolling or reader.paging
                if type(navigation) ~= "table" then return end
                local goto_page = navigation.onGotoPage
                if type(goto_page) ~= "function" then return end
                goto_page(navigation, target)
            end)
            if not jumped then
                logger.warn("LightHouse: page jump failed:", tostring(jump_error))
            end
        end)
    end)
    if not scheduled then
        logger.warn("LightHouse: page jump not scheduled:", tostring(raise))
        return false
    end
    return true
end

--- Shows one highlight's own text when its book cannot be opened.
-- @tparam table group book this highlight belongs to
-- @tparam table annotation normalized annotation
function LightHouse:showHighlightNote(group, annotation)
    local lines = {}
    local title = Status.str(group and group.title)
    if title ~= "" then lines[#lines + 1] = title end
    local chapter = Status.str(annotation and annotation.chapter)
    if chapter ~= "" then lines[#lines + 1] = chapter end
    local text = Sidecar.annotationText(annotation)
    if text ~= "" then lines[#lines + 1] = text end
    local note = Sidecar.annotationNote(annotation)
    if note ~= "" and note ~= text then lines[#lines + 1] = note end
    local page = Sidecar.annotationPage(annotation)
    if page then lines[#lines + 1] = T(_("Page %1"), page) end
    local datetime = Status.str(annotation and annotation.datetime)
    if datetime ~= "" then lines[#lines + 1] = datetime end
    if #lines == 0 then lines[#lines + 1] = _("This highlight has no text.") end
    UIManager:show(squareWidget(TextViewer, {
        title = _("Highlight"),
        text = table.concat(lines, "\n\n"),
    }))
end

--- Fetches and normalizes `GET /api/kosync/stats`.
-- Exactly one request per view open: the payload already carries every derived
-- number (sessions, streaks, daily time, heatmap, health, goal), so the device
-- recomputes nothing and never polls. `JSON.decode` runs inside this function
-- so `withSpinner` turns a malformed body into a notice instead of a raise.
-- @treturn table|nil normalized stats
-- @treturn string|nil error code
--- Fetches and normalizes the reading-statistics payload.
-- One request for the whole screen: the numbers, the heatmap, the recent
-- sessions and the currently-reading books all come from `/api/kosync/stats`,
-- so the page cannot show a headline from one snapshot next to a bar from
-- another.
-- @treturn table|nil { numbers = normalized stats, sessions = normalized sessions }
-- @treturn string|nil error code
function LightHouse:fetchStats()
    local body, err = Client.get(config, "/api/kosync/stats")
    if type(body) ~= "string" or body == "" then
        return nil, err or "invalid_response"
    end
    local decoded_ok, decoded = pcall(JSON.decode, body)
    if not decoded_ok or type(decoded) ~= "table" then
        return nil, "invalid_response"
    end
    local numbers = Stats.normalize(decoded)
    if not numbers then return nil, "invalid_response" end
    return {
        numbers = numbers,
        -- The currently-reading rows are normalized by the module that owns
        -- KOSync rows (`Status.normalizeSessions`), not re-derived here: one
        -- normalizer, one shape, and the same local-sidecar merge the shelf uses.
        sessions = Status.normalizeSessions(decoded.activeBooks),
    }
end

--- Layout of the statistics page, cached per screen size.
-- @treturn table plan
function LightHouse:statsPlan()
    local key = tostring(screenWidth()) .. "x" .. tostring(screenHeight())
    if self._stats_plan and self._stats_plan_key == key then
        return self._stats_plan
    end
    local plan = Ui.pagePlan(screenWidth(), screenHeight(), screenScale())
    self._stats_plan = plan
    self._stats_plan_key = key
    return plan
end

--- Opens the Reading stats view.
--
-- ONE page. The old screen expanded a row per heatmap week, which is what made
-- it ten pages long; the picture is now drawn as a 52-week grid of rects and the
-- four bands around it are laid out to the height the screen reports, so nothing
-- scrolls, nothing pages and every number still comes from the server.
function LightHouse:showStats()
    if not Client.isConfigured(config) then
        self:showProblem{
            title = _("Reading stats"),
            headline = errorHeadline("not_configured"),
            detail = describeError("not_configured"),
            actions = { connectionAction(self) },
        }
        return
    end
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function() self:showStats() end)
        return
    end

    local payload, err = self:withSpinner(_("Loading reading statistics…"), function()
        return self:fetchStats()
    end)
    if not payload or type(payload.numbers) ~= "table" then
        self:showProblem{
            title = _("Reading stats"),
            headline = errorHeadline(err),
            detail = describeError(err),
            actions = { retryAction(_("Try again"), function() self:showStats() end) },
        }
        return
    end

    local plan = self:statsPlan()
    local sessions = payload.sessions or {}

    -- Covers for the reading rows, bounded by what the plan can draw.
    local cover_ids = {}
    for session_index = 1, #sessions do
        if #cover_ids >= plan.reading_rows then break end
        local book_id = Status.num(sessions[session_index].book_id)
        if book_id then cover_ids[#cover_ids + 1] = book_id end
    end
    self:prefetchCoverIds(cover_ids)

    local model = Views.statsModel(payload.numbers, sessions, os.time(), {
        labels = self:pageLabels(),
        weeks = plan.heat_weeks,
        year = os.date("*t").year,
        today = os.date("*t"),
        average_daily_minutes = payload.numbers.averageDailyMinutes,
        reading_max = plan.reading_rows,
        session_max = plan.session_rows,
    })

    -- The statistics page is not the library: the overflow menu offers refresh
    -- and the library, not the grouping switch.
    self.library_state = nil
    self:showPage(model, plan, {
        on_action = function(action)
            if action.kind == "book" then self:openBookDetails(action.entry) end
        end,
    })
end

--- Downloads a book by its resolved Calibre id (used by the reading shelf).
-- @tparam table session normalized KOSync session
function LightHouse:downloadBookId(session)
    local book_id = Status.num(session and session.book_id)
    if not book_id then return end
    book_id = math.floor(book_id)
    local entry = {
        book_id = book_id,
        title = Status.str(session.title),
        authors = Status.str(session.authors),
        download_href = Client.buildUrl(config, string.format("/api/books/%d/download/epub", book_id)),
    }
    self:downloadEntry(entry)
end

--- Prepares and starts an EPUB download.
-- @tparam table entry OPDS entry (or synthetic entry with download_href)
function LightHouse:downloadEntry(entry)
    if not entry.download_href then
        notice(_("This book has no EPUB download link."))
        return
    end
    local dir = self:getDownloadDir()
    if not makeDirs(dir) then
        notice(T(_("Cannot create the download folder %1"), dir))
        return
    end
    local filepath = dir .. "/" .. buildFilename(entry)

    if lfs.attributes(filepath, "mode") == "file" then
        UIManager:show(squareWidget(require("ui/widget/confirmbox"), {
            text = T(_("“%1” is already in the download folder. Download it again?"), buildFilename(entry)),
            ok_text = _("Download again"),
            ok_cb = function() self:startDownload(entry, filepath) end,
        }))
        return
    end
    self:startDownload(entry, filepath)
end

--- Performs the blocking download and offers to open the file.
-- @tparam table entry OPDS entry
-- @string filepath destination
function LightHouse:startDownload(entry, filepath)
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function() self:startDownload(entry, filepath) end)
        return
    end

    local ok, err = self:withSpinner(T(_("Downloading %1…"), entry.title or ""), function()
        return Client.download(config, entry.download_href, filepath)
    end)

    if not ok then
        -- An InfoMessage, not a failure screen: this runs after the reader chose
        -- a book, so replacing the catalog behind them would lose their place.
        -- The message still leads with what failed and then what to do.
        notice(errorHeadline(err) .. "\n" .. describeError(err), 6)
        return
    end

    if self.ui and self.ui.onRefresh then
        pcall(function() self.ui:onRefresh() end)
    end

    UIManager:show(squareWidget(require("ui/widget/confirmbox"), {
        text = T(_("Saved to:\n%1"), filepath),
        cancel_text = _("Close"),
        ok_text = _("Open now"),
        ok_cb = function()
            local ReaderUI = require("apps/reader/readerui")
            ReaderUI:showReader(filepath)
        end,
    }))
end

--- Shows (or re-uses) the results menu.
-- The page geometry comes from `Ui.layout`, so every view shares one row
-- rhythm: the same margins, the same one-line rows, and a left gutter exactly
-- as wide as the cover slot on views that draw covers.
-- @string title menu title
-- @tparam table items item_table
-- @tparam[opt] table options { covers = boolean, layout = table }
function LightHouse:showMenu(title, items, options)
    options = options or {}
    local layout = options.layout or self:layoutFor(options.covers == true)
    local gutter = options.covers == true and layout.gutter or 0
    if self.menu then
        -- A new top-level view must not inherit the previous submenu back-stack.
        self.menu.item_table_stack = {}
        self.menu.items_per_page = layout.rows
        self.menu.state_w = gutter
        self.menu:switchItemTable(title, items)
        return
    end
    self.menu = squareWidget(Menu, {
        title = title,
        item_table = items,
        title_multilines = true,
        items_per_page = layout.rows,
        state_w = gutter,
        close_callback = function() self.menu = nil end,
    })
    UIManager:show(self.menu)
end

