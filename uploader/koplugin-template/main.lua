--- Runs a blocking server call behind a spinner.
-- KOReader is single threaded; this is the pattern its own plugins use
-- (show InfoMessage → forceRePaint → blocking call → close).
-- @string text spinner label
-- @function func callable returning body, err
-- @treturn string|nil body
-- @treturn string|nil err
function LightHouse:withSpinner(text, func)
    local info = InfoMessage:new{ text = text, dismissable = false }
    UIManager:show(info)
    UIManager:forceRePaint()
    local ok, body, err = pcall(func)
    UIManager:close(info)
    if not ok then
        -- `body` holds the raised error value: either a message string or a
        -- table carrying message + traceback, depending on how it was thrown.
        local message
        if type(body) == "table" then
            local detail = body.message or body.traceback
            message = detail ~= nil and tostring(detail) or ("unknown " .. type(body) .. " error")
            logger.warn("LightHouse: request raised:", message, body.traceback)
        else
            message = tostring(body)
            logger.warn("LightHouse: request raised:", message)
        end
        return nil, "exception: " .. message
    end
    if body == nil and err ~= nil then
        logger.warn("LightHouse: request failed:", tostring(err))
    end
    return body, err
end

--- Fetches normalized KOSync sessions; failures degrade to "no status".
-- @treturn table array of normalized sessions (possibly empty)
function LightHouse:fetchSessions()
    local body = Client.get(config, "/api/kosync/active")
    if type(body) ~= "string" or body == "" then return {} end
    local decoded = JSON.decode(body)
    if type(decoded) ~= "table" then return {} end
    return Status.normalizeSessions(decoded)
end

--- Opens a catalog page.
-- @string query search terms ("" for the whole library)
-- @int start_index zero-based offset into the result set
-- @int page_number 1-based page number for the title bar
function LightHouse:openCatalog(query, start_index, page_number)
    if not Client.isConfigured(config) then
        notice(describeError("not_configured"))
        return
    end
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function()
            self:openCatalog(query, start_index, page_number)
        end)
        return
    end

    local path = "/api/opds?" .. buildQuery({
        search = query or "",
        start = start_index or 0,
        count = pageSize(),
    })

    local body, err = self:withSpinner(_("Loading LightHouse catalog…"), function()
        return Client.get(config, path)
    end)
    if not body then
        notice(describeError(err))
        return
    end

    local feed = OPDS.parse(body)
    if #feed.entries == 0 and (query or "") ~= "" then
        notice(T(_("No books match “%1”."), query))
        return
    end

    local sessions = self:withSpinner(_("Checking reading progress…"), function()
        return self:fetchSessions()
    end) or {}
    Status.merge(feed.entries, sessions)

    local title
    if (query or "") ~= "" then
        title = T(_("Search: %1 (page %2)"), query, page_number or 1)
    else
        title = T(_("LightHouse library (page %1)"), page_number or 1)
    end

    local items = {}
    items[#items + 1] = {
        text = _("🔍 Search library…"),
        callback = function() self:showSearchDialog() end,
    }
    for entry_index = 1, #feed.entries do
        items[#items + 1] = self:buildCatalogItem(feed.entries[entry_index])
    end

    if feed.next_href and #feed.entries > 0 then
        items[#items + 1] = {
            text = _("Next page ▸"),
            bold = true,
            callback = function()
                self:openCatalog(query, (start_index or 0) + #feed.entries, (page_number or 1) + 1)
            end,
        }
    end

    self:showMenu(title, items)
end

--- Builds one catalog row, including rating, progress and the detail submenu.
-- @tparam table entry OPDS entry with optional .status
-- @treturn table Menu item
function LightHouse:buildCatalogItem(entry)
    local stars = ""
    if entry.rating and entry.rating > 0 then
        stars = Status.ratingStars(entry.rating) .. " "
    end

    local details = {}
    details[#details + 1] = {
        text = _("Download EPUB"),
        bold = true,
        enabled = entry.download_href ~= nil,
        callback = function() self:downloadEntry(entry) end,
    }
    details[#details + 1] = {
        text = T(_("Author: %1"), entry.authors ~= "" and entry.authors or _("Unknown")),
        callback = function() end,
    }
    if entry.series and entry.series ~= "" then
        details[#details + 1] = {
            text = entry.series_index
                and T(_("Series: %1 #%2"), entry.series, entry.series_index)
                or T(_("Series: %1"), entry.series),
            callback = function() end,
        }
    end
    details[#details + 1] = {
        text = T(_("Rating: %1"), Status.ratingLabel(entry.rating)),
        callback = function() end,
    }
    details[#details + 1] = {
        text = T(_("Progress: %1"), Status.statusLabel(entry)),
        callback = function() end,
    }
    if entry.status and entry.status.device and entry.status.device ~= "" then
        details[#details + 1] = {
            text = T(_("Last device: %1"), entry.status.device),
            callback = function() end,
        }
    end
    if (entry.summary and entry.summary ~= "") or (entry.content and entry.content ~= "") then
        details[#details + 1] = {
            text = _("Synopsis"),
            callback = function() self:showSynopsis(entry) end,
        }
    end
    if entry.tags and #entry.tags > 0 then
        details[#details + 1] = {
            text = T(_("Tags: %1"), table.concat(entry.tags, ", ")),
            callback = function() end,
        }
    end

    local mandatory = entry.authors ~= "" and entry.authors or _("Unknown")
    mandatory = mandatory .. "  " .. Status.statusLabel(entry)

    return {
        text = stars .. (entry.title ~= "" and entry.title or _("Untitled")),
        mandatory = mandatory,
        sub_item_table = details,
    }
end

--- Shows the synopsis/description of one book.
-- @tparam table entry OPDS entry
function LightHouse:showSynopsis(entry)
    local text = entry.content ~= "" and entry.content or entry.summary
    if not text or text == "" then
        notice(_("No synopsis available for this book."))
        return
    end
    UIManager:show(TextViewer:new{
        title = entry.title,
        text = text,
        justified = true,
    })
end

--- Opens the search dialog.
function LightHouse:showSearchDialog()
    local dialog
    dialog = InputDialog:new{
        title = _("Search the LightHouse library"),
        input = "",
        input_hint = _("Title, author or series"),
        buttons = {
            {
                {
                    text = _("Cancel"),
                    id = "close",
                    callback = function() UIManager:close(dialog) end,
                },
                {
                    text = _("Search"),
                    is_enter_default = true,
                    callback = function()
                        local query = dialog:getInputText()
                        UIManager:close(dialog)
                        query = query and query:gsub("^%s+", ""):gsub("%s+$", "") or ""
                        if query == "" then
                            self:openCatalog("", 0, 1)
                        else
                            self:openCatalog(query, 0, 1)
                        end
                    end,
                },
            },
        },
    }
    UIManager:show(dialog)
    dialog:onShowKeyboard()
end

--- Shows every active KOSync session, newest first.
function LightHouse:showReading()
    if not Client.isConfigured(config) then
        notice(describeError("not_configured"))
        return
    end
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function() self:showReading() end)
        return
    end

    local sessions, err = self:withSpinner(_("Loading reading progress…"), function()
        return self:fetchSessions()
    end)
    if not sessions then
        notice(describeError(err))
        return
    end
    if #sessions == 0 then
        notice(_("No reading progress has been synced yet."))
        return
    end

    local items = {}
    -- `session_index`, not `_`: `_` is gettext in this file (see the note by
    -- its require), so using it as a throwaway aborted the whole process on
    -- the device the moment a row called `_("…")`.
    for session_index = 1, #sessions do
        local session = sessions[session_index]
        local details = {}
        if session.book_id then
            details[#details + 1] = {
                text = _("Download EPUB"),
                bold = true,
                callback = function() self:downloadBookId(session) end,
            }
        else
            details[#details + 1] = {
                text = _("No matching book in the library"),
                enabled = false,
                callback = function() end,
            }
        end
        details[#details + 1] = {
            text = T(_("Progress: %1"), Status.progressBar(session.percentage)),
            callback = function() end,
        }
        if session.device and session.device ~= "" then
            details[#details + 1] = {
                text = T(_("Device: %1"), session.device),
                callback = function() end,
            }
        end
        if session.filename and session.filename ~= "" then
            details[#details + 1] = {
                text = T(_("File: %1"), session.filename),
                callback = function() end,
            }
        end

        local mandatory = session.authors ~= "" and session.authors or _("Unknown")
        items[#items + 1] = {
            text = (session.title ~= "" and session.title) or _("Untitled"),
            mandatory = mandatory .. "  " .. Status.progressBar(session.percentage),
            sub_item_table = details,
        }
    end

    self:showMenu(_("Currently reading"), items)
end

--- Fetches and normalizes `GET /api/kosync/stats`.
-- Exactly one request per view open: the payload already carries every derived
-- number (sessions, streaks, daily time, heatmap, health, goal), so the device
-- recomputes nothing and never polls. `JSON.decode` runs inside this function
-- so `withSpinner` turns a malformed body into a notice instead of a raise.
-- @treturn table|nil normalized stats
-- @treturn string|nil error code
function LightHouse:fetchStats()
    local body, err = Client.get(config, "/api/kosync/stats")
    if type(body) ~= "string" or body == "" then
        return nil, err or "invalid_response"
    end
    local stats = Stats.normalize(JSON.decode(body))
    if not stats then return nil, "invalid_response" end
    return stats
end

--- Non-tappable section heading for the stats view.
-- @string text
-- @treturn table Menu item
local function statsSection(text)
    return { text = text, enabled = false, callback = function() end }
end

--- Read-only stats row: label on the left, value on the right.
-- A value the server did not send renders "unavailable"; zero stays zero.
-- @string label
-- @string|nil value
-- @treturn table Menu item
local function statsRow(label, value)
    return {
        text = label,
        mandatory = value or _("unavailable"),
        callback = function() end,
    }
end

--- Shade key for the heatmap, built from the module's own level thresholds so
-- the printed key and the picture above it can never disagree.
-- @treturn string
local function heatmapKeyLabel()
    local thresholds = Stats.LEVEL_MIN_MINUTES
    local top_level = 0
    for level in pairs(thresholds) do
        if level > top_level then top_level = level end
    end

    local parts = { Stats.heatmapGlyph(0) .. " " .. _("none") }
    for level = 1, top_level do
        local text
        if level == top_level then
            text = T(_("%1 or more"), Stats.formatMinutes(thresholds[level]))
        else
            text = T(_("under %1"), Stats.formatMinutes(thresholds[level + 1]))
        end
        parts[#parts + 1] = Stats.heatmapGlyph(level) .. " " .. text
    end
    return T(_("Shade key: %1"), table.concat(parts, " · "))
end

--- Builds the rows of the Reading stats view.
-- Order is deliberate: the numbers a reader checks daily come first, then
-- library health, then the yearly goal (only when one is set), then the
-- 26-week activity picture, which is the tallest section and scrolls.
-- @tparam table stats normalized stats from `fetchStats`
-- @treturn table array of Menu items
function LightHouse:buildStatsItems(stats)
    local items = {}

    -- 1. Streak, current with best.
    items[#items + 1] = statsRow(_("Current streak"), Stats.streakLabel(stats.streaks))

    -- 2. Reading time: today, this week, all time.
    local time = stats.time or {}
    local time_rows = {
        { label = _("Read today"), value = Stats.formatDuration(time.todaySeconds) },
        { label = _("Read this week"), value = Stats.formatDuration(time.thisWeekSeconds) },
        { label = _("Total reading time"), value = Stats.formatHours(time.totalHours) },
    }
    for row_index = 1, #time_rows do
        items[#items + 1] = statsRow(time_rows[row_index].label, time_rows[row_index].value)
    end

    -- 3. Books finished this year (the server counts finished timestamps).
    items[#items + 1] = statsRow(_("Books finished this year"), Stats.formatCount(stats.finishedThisYear))

    -- 4. Library health as three counts.
    items[#items + 1] = statsSection(_("Library health"))
    local health = stats.health or {}
    items[#items + 1] = statsRow(_("Unread"), Stats.formatCount(health.unread))
    items[#items + 1] = statsRow(_("Reading"), Stats.formatCount(health.reading))
    items[#items + 1] = statsRow(_("Finished"), Stats.formatCount(health.finished))

    -- 5. Yearly goal, only when a target is configured.
    local goal = stats.goal
    if goal then
        local heading = goal.year and T(_("Yearly goal %1"), Stats.formatCount(goal.year)) or _("Yearly goal")
        items[#items + 1] = statsSection(heading)

        -- Bars reuse Status.progressBar, the plugin's existing renderer, so a
        -- goal row looks like every other progress row on the device.
        local goal_rows = {
            { label = _("Books"), ratio = goal.booksRatio, value = Stats.goalBooksLabel(goal) },
            { label = _("Hours"), ratio = goal.hoursRatio, value = Stats.goalHoursLabel(goal) },
        }
        for row_index = 1, #goal_rows do
            local goal_row = goal_rows[row_index]
            local value = goal_row.value
            if value and goal_row.ratio then
                value = Status.progressBar(goal_row.ratio) .. " · " .. value
            end
            items[#items + 1] = statsRow(goal_row.label, value)
        end
    end

    -- 6. Activity heatmap: one menu row per week of up to seven days.
    items[#items + 1] = statsSection(_("Activity (newest week last)"))
    local weeks = Stats.heatmapRows(stats.heatmap)
    if #weeks == 0 then
        items[#items + 1] = statsRow(_("Heatmap"), nil)
    end
    for week_index = 1, #weeks do
        local week = weeks[week_index]
        local days = {}
        for day_index = 1, #week do
            local day = week[day_index]
            days[#days + 1] = {
                text = T(_("%1 · %2"), Stats.shortDate(day.date) or day.date, Stats.dayDurationLabel(day) or _("unavailable")),
                callback = function() self:showDayStats(day) end,
            }
        end
        items[#items + 1] = {
            text = Stats.heatmapRowText(week),
            mandatory = Stats.shortDate(week[#week].date),
            sub_item_table = days,
        }
    end
    items[#items + 1] = statsSection(heatmapKeyLabel())

    return items
end

--- Opens the Reading stats view.
function LightHouse:showStats()
    if not Client.isConfigured(config) then
        notice(describeError("not_configured"))
        return
    end
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function() self:showStats() end)
        return
    end

    local stats, err = self:withSpinner(_("Loading reading statistics…"), function()
        return self:fetchStats()
    end)
    if not stats then
        notice(describeError(err))
        return
    end

    self:showMenu(_("Reading stats"), self:buildStatsItems(stats))
end

--- Shows the reading time recorded on one heatmap day.
-- @tparam table day normalized heatmap day
function LightHouse:showDayStats(day)
    local lines = { day.date }
    lines[#lines + 1] = T(_("Reading time: %1"), Stats.dayDurationLabel(day) or _("unavailable"))
    if day.count then
        lines[#lines + 1] = T(_("Sessions: %1"), Stats.formatCount(day.count))
    end
    if day.bookCount then
        lines[#lines + 1] = T(_("Books: %1"), Stats.formatCount(day.bookCount))
    end
    UIManager:show(TextViewer:new{
        title = _("Reading on this day"),
        text = table.concat(lines, "\n"),
    })
end

--- Downloads a book by its resolved Calibre id (used by the reading shelf).
-- @tparam table session normalized KOSync session
function LightHouse:downloadBookId(session)
    local entry = {
        book_id = session.book_id,
        title = session.title,
        authors = session.authors,
        download_href = Client.buildUrl(config, string.format("/api/books/%d/download/epub", session.book_id)),
    }
    self:downloadEntry(entry)
end

--- Prepares and starts an EPUB download.
-- @tparam table entry OPDS entry (or synthetic entry with download_href)
function LightHouse:downloadEntry(entry)
    if not entry.download_href then
        notice(_("This book has no EPUB download link."))
        return
    end
    local dir = self:getDownloadDir()
    if not makeDirs(dir) then
        notice(T(_("Cannot create the download folder %1"), dir))
        return
    end
    local filepath = dir .. "/" .. buildFilename(entry)

    if lfs.attributes(filepath, "mode") == "file" then
        UIManager:show(require("ui/widget/confirmbox"):new{
            text = T(_("“%1” is already in the download folder. Download it again?"), buildFilename(entry)),
            ok_text = _("Download again"),
            ok_cb = function() self:startDownload(entry, filepath) end,
        })
        return
    end
    self:startDownload(entry, filepath)
end

--- Performs the blocking download and offers to open the file.
-- @tparam table entry OPDS entry
-- @string filepath destination
function LightHouse:startDownload(entry, filepath)
    if not NetworkMgr:isOnline() then
        NetworkMgr:willRerunWhenOnline(function() self:startDownload(entry, filepath) end)
        return
    end

    local ok, err = self:withSpinner(T(_("Downloading %1…"), entry.title or ""), function()
        return Client.download(config, entry.download_href, filepath)
    end)

    if not ok then
        notice(describeError(err))
        return
    end

    if self.ui and self.ui.onRefresh then
        pcall(function() self.ui:onRefresh() end)
    end

    UIManager:show(require("ui/widget/confirmbox"):new{
        text = T(_("Saved to:\n%1"), filepath),
        cancel_text = _("Close"),
        ok_text = _("Open now"),
        ok_cb = function()
            local ReaderUI = require("apps/reader/readerui")
            ReaderUI:showReader(filepath)
        end,
    })
end

--- Shows (or re-uses) the results menu.
-- @string title menu title
-- @tparam table items item_table
function LightHouse:showMenu(title, items)
    if self.menu then
        -- A new top-level view must not inherit the previous submenu back-stack.
        self.menu.item_table_stack = {}
        self.menu:switchItemTable(title, items)
        return
    end
    self.menu = Menu:new{
        title = title,
        item_table = items,
        title_multilines = true,
        close_callback = function() self.menu = nil end,
    }
    UIManager:show(self.menu)
end

