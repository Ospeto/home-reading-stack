--- Forgets the kept sidecar directory list, so the next scan walks the tree.
-- Called when this plugin changed the library itself: a book it just saved has
-- a sidecar the kept list cannot know about. Removal failure is silent - the
-- worst it costs is one walk.
local function forgetSidecarList()
    pcall(os.remove, sidecarListPath())
end

--- The sidecar directories a recent walk found, when the list is still fresh.
-- Holds paths only, never what a sidecar says, so nothing a reader sees is
-- served from here; the window bounds how long a sidecar created since the last
-- walk can go unseen (a book copied on, or one opened in KOReader since), and a
-- download through this plugin deletes the list outright.
-- @treturn table|nil array of `*.sdr` directory paths
local function keptSidecarList()
    local path = sidecarListPath()
    local stamp = lfs.attributes(path, "modification")
    if type(stamp) ~= "number" then return nil end
    local age = os.time() - stamp
    if age < 0 or age > LightHouse.SIDECAR_LIST_TTL_SECONDS then return nil end
    local handle = io.open(path, "rb")
    if not handle then return nil end
    local body
    pcall(function() body = handle:read("*a") end)
    pcall(handle.close, handle)
    if type(body) ~= "string" or body == "" then return nil end
    local directories = {}
    for line in body:gmatch("[^\r\n]+") do
        if line ~= "" then directories[#directories + 1] = line end
    end
    if #directories == 0 then return nil end
    return directories
end

--- Remembers the sidecar directories a walk found.
-- Failing to write costs the next walk, never a record.
-- @tparam table directories
local function rememberSidecarList(directories)
    if type(directories) ~= "table" or #directories == 0 then return end
    if not makeDirs(cacheDir()) then return end
    local handle = io.open(sidecarListPath(), "wb")
    if not handle then return end
    pcall(function() handle:write(table.concat(directories, "\n") .. "\n") end)
    pcall(handle.close, handle)
end

--- Cached cover path for an entry, or nil when the book has no usable id.
-- @tparam table entry
-- @treturn string|nil
local function coverPath(entry)
    if type(entry) ~= "table" or not entry.book_id then return nil end
    local name = Ui.coverCacheName(entry.book_id)
    if not name then return nil end
    return coverDir() .. "/" .. name
end

--- Negative-cache marker for a book the server has no cover for.
-- @tparam table entry
-- @treturn string|nil
local function coverMissPath(entry)
    if type(entry) ~= "table" or not entry.book_id then return nil end
    local name = Ui.coverMissName(entry.book_id)
    if not name then return nil end
    return coverDir() .. "/" .. name
end

--- True when a cache file holds a whole JPEG rather than a truncated one.
-- A download cut off mid-flight leaves a file that starts with a valid JPEG
-- header and has a fresh mtime, so the end-of-image marker is what separates a
-- complete cover from a half-written one. A half-written cover must never
-- reach `ImageWidget`: it would raise in the paint pass, where nothing can
-- catch it.
-- @string path
-- @treturn boolean
local function coverFileWhole(path)
    if type(path) ~= "string" then return false end
    local handle = io.open(path, "rb")
    if not handle then return false end
    local head = handle:read(2) or ""
    local tail = ""
    if (handle:seek("end") or 0) >= 2 then
        handle:seek("end", -2)
        tail = handle:read(2) or ""
    end
    handle:close()
    return head == "\255\216" and tail == "\255\217"
end

--- True when this row's cover is neither cached nor known to be missing.
-- @tparam table entry
-- @number now unix seconds
-- @treturn boolean
local function coverNeedsFetch(entry, now)
    local path = coverPath(entry)
    if not path then return false end
    if type(entry.thumbnail_href) ~= "string" or entry.thumbnail_href == "" then
        return false
    end
    if Ui.isFresh(lfs.attributes(path, "modification"), now) and coverFileWhole(path) then
        return false
    end
    local miss = coverMissPath(entry)
    if miss and Ui.isFresh(lfs.attributes(miss, "modification"), now) then
        return false
    end
    return true
end

--- KOReader widgets a cover slot needs, loaded once and only if used.
-- Lazy and pcall-guarded: a build that lacks one of these must still open the
-- catalog, just without images, instead of failing at load time.
local coverWidgets
local function loadCoverWidgets()
    if coverWidgets ~= nil then return coverWidgets or nil end
    local ok, loaded = pcall(function()
        return {
            image = require("ui/widget/imagewidget"),
            frame = require("ui/widget/container/framecontainer"),
            center = require("ui/widget/container/centercontainer"),
            text = require("ui/widget/textwidget"),
            font = require("ui/font"),
            geom = require("ui/geometry"),
        }
    end)
    coverWidgets = ok and loaded or false
    if coverWidgets == false then return nil end
    return coverWidgets
end

--- Neutral cover slot: a framed box with a book glyph, never a blank hole.
-- The same slot is used while a cover loads and for a book the server has no
-- cover for, so a coverless book keeps the row's shape instead of breaking the
-- page or drawing an error.
-- @tparam table layout result of `Ui.layout`
-- @treturn table|nil widget
local function coverPlaceholder(layout)
    local widgets = loadCoverWidgets()
    if not widgets then return nil end
    local border = math.max(math.floor(screenScale()), 1)
    local inner = widgets.geom:new{
        w = math.max(layout.cover_width - 2 * border, 1),
        h = math.max(layout.cover_height - 2 * border, 1),
    }
    return widgets.frame:new{
        radius = Ui.tokens.corner_radius,
        bordersize = border,
        padding = 0,
        widgets.center:new{
            dimen = inner,
            widgets.text:new{
                text = Ui.GLYPH.cover,
                face = widgets.font:getFace("smallinfofont"),
            },
        },
    }
end

--- Left-gutter marker for a row that is not a book (search, next page).
-- Keeps the gutter aligned instead of leaving an empty notch on those rows.
-- @tparam table layout result of `Ui.layout`
-- @string glyph one of `Ui.GLYPH`
-- @treturn table|nil widget
local function markerSlot(layout, glyph)
    local widgets = loadCoverWidgets()
    if not widgets then return nil end
    return widgets.center:new{
        dimen = widgets.geom:new{ w = layout.cover_width, h = layout.cover_height },
        widgets.text:new{
            text = glyph,
            face = widgets.font:getFace("infofont"),
        },
    }
end

--- Short, human headline for a failed request.
-- Deliberately separate from `describeError`: the headline states what failed in
-- one short line, the detail line says what to do about it. A failure screen
-- shows both instead of a bare "something went wrong".
-- @string err
-- @treturn string
local function errorHeadline(err)
    local code = type(err) == "string" and err or tostring(err or "")
    if code == "not_configured" then
        return _("This plugin is not configured")
    elseif code == "https_unavailable" then
        return _("No HTTPS support in this KOReader build")
    elseif code:match("^network_error") then
        return _("Can't reach the LightHouse server")
    elseif code == "empty_response" then
        return _("The server sent an empty response")
    elseif code == "invalid_response" then
        return _("The server response could not be read")
    elseif code == "html_response" then
        return _("The server sent a web page")
    elseif code:match("^file_error") then
        return _("Can't write the download file")
    elseif code:match("^http_401") or code:match("^http_403") then
        return _("The server rejected this device's key")
    elseif code == "too_many_redirects" or code == "invalid_redirect" then
        return _("The server sent a bad redirect")
    elseif code:match("^http_") then
        return T(_("Server error %1"), code:gsub("^http_", ""))
    end
    return _("The request failed")
end

--- The two faces a row is drawn with, resolved the way KOReader resolves them.
--
-- `Menu:updateItems` picks the row font from the item count
-- (`Menu.getItemFontSize`) or the reader's own `items_font_size` override, and
-- the metadata column is four points smaller unless `items_mandatory_font_size`
-- says otherwise. Measuring with any other size would make the budget fiction.
-- @number rows items per page for this view
-- @treturn table|nil { face, info_face, font_size, info_size }
local function rowFaces(rows)
    if type(Font) ~= "table" or type(Font.getFace) ~= "function" then return nil end
    local per_page = tonumber(rows) or 0
    local item_setting, mandatory_setting
    pcall(function()
        item_setting = G_reader_settings:readSetting("items_font_size")
        mandatory_setting = G_reader_settings:readSetting("items_mandatory_font_size")
    end)
    local font_size = tonumber(item_setting)
    if not font_size and type(Menu.getItemFontSize) == "function" then
        local ok, value = pcall(Menu.getItemFontSize, per_page)
        if ok then font_size = tonumber(value) end
    end
    -- Same formula as `Menu.getItemFontSize`, for a build that lacks the class.
    font_size = font_size or math.floor(24 - ((per_page - 6) / 18) * 10)
    if font_size < 1 then return nil end
    local info_size = tonumber(mandatory_setting) or (font_size - 4)
    if info_size < 1 then info_size = 1 end
    local ok_face, face = pcall(Font.getFace, Font, "smallinfofont", font_size)
    local ok_info, info_face = pcall(Font.getFace, Font, "infont", info_size)
    if not ok_face or not face or not ok_info or not info_face then return nil end
    return {
        face = face,
        info_face = info_face,
        font_size = font_size,
        info_size = info_size,
    }
end

--- A measuring function for one face, or nil when this build cannot measure.
--
-- KOReader's own `TextWidget:getWidth` is the only measurement that matches what
-- the device paints with, so the row budget is built from it and nowhere else.
-- Widths are cached: one page re-measures the same authors on every page turn.
-- @param face
-- @boolean bold
-- @treturn function|nil
local function faceMeasurer(face, bold)
    if face == nil then return nil end
    local ok, TextWidget = pcall(require, "ui/widget/textwidget")
    if not ok or type(TextWidget) ~= "table" or type(TextWidget.new) ~= "function" then
        return nil
    end
    local cache = {}
    local cached = 0
    local cache_key = tostring(face) .. (bold == true and "|bold" or "")
    return function(text)
        if type(text) ~= "string" then return nil end
        local key = cache_key .. "\1" .. text
        local hit = cache[key]
        if hit ~= nil then return hit end
        local widget_ok, widget = pcall(TextWidget.new, TextWidget, {
            text = text,
            face = face,
            bold = bold == true,
        })
        if not widget_ok or type(widget) ~= "table" then return nil end
        local width = type(widget.getWidth) == "function" and widget:getWidth() or nil
        if type(widget.free) == "function" then pcall(widget.free, widget) end
        width = tonumber(width)
        -- A cache that grows without bound on a 2000-book library is a leak;
        -- dropping it costs a re-measure, never correctness.
        if cached > 512 then
            cache = {}
            cached = 0
        end
        if width then
            cache[key] = width
            cached = cached + 1
        end
        return width
    end
end

--- The pixel budget a row's metadata column may occupy, cached per layout.
--
-- `menu.lua` computes
--   available_width = content_width - state_width
--                                 - text_mandatory_padding - mandatory_w
-- and hands that straight to a `TextBoxWidget`, whose `makeLine` raises when it
-- is not strictly positive. `state_width` is the gutter this plugin put there
-- and `mandatory_w` is the column this plugin wrote, so both are ours to bound:
-- the metadata column gets a measured pixel budget, and the title column is
-- guaranteed the rest.
-- @tparam table layout result of `Ui.layout`
-- @treturn table|nil { content_width, usable, budget, name_min, measure }
local function rowGeometry(layout)
    if type(layout) ~= "table" then return nil end
    if layout.row_geometry ~= nil then return layout.row_geometry or nil end
    layout.row_geometry = false
    local content_width = rowContentWidth()
    local mandatory_padding = mandatoryPadding()
    local gutter = tonumber(layout.gutter) or 0
    local scale = screenScale()
    local faces = rowFaces(layout.rows)
    local measure = faces and faceMeasurer(faces.face, false) or nil
    local info_measure = faces and faceMeasurer(faces.info_face, false) or nil
    local usable = content_width - gutter - mandatory_padding
    if usable < 1 then usable = 0 end
    local name_min = math.floor(Ui.tokens.name_min_units * scale)
    -- The title column must also be wider than the ellipsis KOReader draws when
    -- it truncates, or the truncated name re-shapes itself to a negative width
    -- (the second call site in the device crash logs).
    local ellipsis_width = Ui.textWidth(Ui.GLYPH.ellipsis, measure) or 0
    if ellipsis_width * 3 > name_min then name_min = math.floor(ellipsis_width * 3) end
    local budget = math.floor(usable * Ui.tokens.mandatory_share)
    local room = usable - name_min
    if room < budget then budget = room end
    if budget < 0 then budget = 0 end
    layout.row_geometry = {
        content_width = content_width,
        usable = usable,
        budget = budget,
        name_min = name_min,
        measure = info_measure,
        title_measure = measure,
    }
    return layout.row_geometry
end

--- Geometry for one view.
-- @boolean with_covers
-- @treturn table result of `Ui.layout`
function LightHouse:layoutFor(with_covers)
    local layout = Ui.layout(screenHeight(), screenScale(), with_covers == true)
    local scale = screenScale()
    -- The cover keeps its place: the gutter is clamped so the title column
    -- always has a drawable width, and only a screen where no cover can leave
    -- one falls back to text rows.
    Ui.clampLayout(layout, {
        content_width = rowContentWidth(),
        padding = mandatoryPadding(),
        scale = scale,
        name_min = math.floor(Ui.tokens.name_min_units * scale),
    })
    if layout.gutter_reduced then
        logger.info("LightHouse: cover slot narrowed to keep the title column drawable")
    end
    return layout
end

