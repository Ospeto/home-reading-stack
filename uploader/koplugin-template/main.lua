--- Maps a client error code to a message the reader can act on.
-- Codes arrive from `lighthouse_client` as plain strings, optionally suffixed
-- with diagnostic detail (`network_error: timeout`); the prefix decides which
-- actionable message the reader sees.
-- @string err
-- @treturn string
local function describeError(err)
    local code = type(err) == "string" and err or tostring(err or "")
    if code == "not_configured" then
        return _("This plugin is not configured. Download it again from the LightHouse server (Guide → KOReader plugin).")
    elseif code:match("^network_error") then
        return _("Could not reach the LightHouse server. Check Wi-Fi and the server address in the Connection screen.")
    elseif code == "https_unavailable" then
        return _("This KOReader build has no TLS support, so it cannot reach an https:// server. Use the LAN http:// address instead.")
    elseif code == "empty_response" then
        return _("The server returned an empty file.")
    elseif code == "invalid_response" then
        return _("The server sent reading statistics this plugin could not read. Download the plugin again from the LightHouse web app (Guide → KOReader plugin).")
    elseif code == "html_response" then
        return _("The server returned a web page instead of the file. Check the server address, or open the web app and sign in again.")
    elseif code:match("^file_error") then
        return T(_("Could not write the file: %1"), code:gsub("^file_error:%s*", ""))
    elseif code == "too_many_redirects" then
        return _("The server redirected the request too many times. Download the plugin again from the LightHouse web app.")
    elseif code == "invalid_redirect" then
        return _("The server sent a redirect the plugin could not follow. Download the plugin again from the LightHouse web app.")
    elseif code:match("^exception:") then
        return T(_("The request failed: %1"), code:gsub("^exception:%s*", ""))
    elseif code:match("^http_401") or code:match("^http_403") then
        return _("The server rejected this device's key. Download the plugin again from the LightHouse web app.")
    elseif code:match("^http_") then
        return T(_("The server returned an error (%1)."), code:gsub("^http_", ""))
    end
    return _("Something went wrong.")
end

--- Recursively creates a directory path.
-- @string path
-- @treturn boolean
local function makeDirs(path)
    if lfs.attributes(path, "mode") == "directory" then return true end
    local parts = {}
    for part in path:gmatch("[^/]+") do parts[#parts + 1] = part end
    local current = path:sub(1, 1) == "/" and "" or "."
    for part_index = 1, #parts do
        current = current .. "/" .. parts[part_index]
        if lfs.attributes(current, "mode") ~= "directory" then
            lfs.mkdir(current)
        end
    end
    return lfs.attributes(path, "mode") == "directory"
end

--- Truncates a string to at most `max_bytes` bytes without splitting a UTF-8
-- sequence, so Burmese titles never produce invalid bytes on disk.
-- @string text
-- @number max_bytes
-- @treturn string
local function truncateUtf8(text, max_bytes)
    if #text <= max_bytes then return text end
    local cut = max_bytes
    while cut > 0 do
        local byte = text:byte(cut + 1)
        -- Stop when the byte after the cut is not a continuation byte.
        if not byte or byte < 0x80 or byte >= 0xC0 then break end
        cut = cut - 1
    end
    if cut < 1 then cut = max_bytes end
    return text:sub(1, cut)
end

--- Formats a Calibre series index for a filename.
-- Calibre allows fractional indices (a novella at 1.5) and the OPDS feed can
-- carry a string or a float; formatting a non-integer with `%02d` raises in
-- some Lua builds, so the integer part is formatted and the fraction kept.
-- @param index number or numeric string
-- @treturn string|nil e.g. "01", "01.5" (nil when the index is unusable)
local function formatSeriesIndex(index)
    local value = tonumber(index)
    if not value or value ~= value then return nil end -- nil or NaN
    if value < 0 then value = 0 end
    if value > 9999 then value = 9999 end

    local whole = math.floor(value)
    local fraction = value - whole
    if fraction < 0.005 then
        return string.format("%02d", whole)
    end
    local decimals = string.format("%.2f", value)
        :gsub("^%d+", "")
        :gsub("0+$", "")
        :gsub("%.$", "")
    return string.format("%02d", whole) .. decimals
end

--- Builds a filesystem-safe EPUB filename from catalog metadata.
-- Mirrors the server's own download naming ("Title - Author.epub") without
-- ever touching the Calibre storage path.
-- @tparam table entry OPDS entry
-- @treturn string
local function buildFilename(entry)
    entry = entry or {}

    local function sanitize(value)
        value = tostring(value or "")
        value = value:gsub("[/\\:*?\"<>|]", "_")
        value = value:gsub("%s+", " ")
        value = value:gsub("^%s+", "")
        value = value:gsub("[%s%.]+$", "")
        return value
    end

    local title = sanitize(entry.title)
    local authors = sanitize(entry.authors)

    local series = sanitize(entry.series)
    if series ~= "" then
        local index = formatSeriesIndex(entry.series_index)
        local prefix = index and (series .. " " .. index) or series
        if title == "" then
            title = prefix
        else
            title = prefix .. " - " .. title
        end
    end

    local name
    if title == "" then
        name = string.format("lighthouse-%s", sanitize(tostring(entry.book_id or "book")))
    elseif authors == "" then
        name = title
    else
        name = title .. " - " .. authors
    end

    name = truncateUtf8(name, MAX_FILENAME_LENGTH):gsub("^%s+", "")
    name = name:gsub("[%s%.]+$", "")
    if name == "" then
        name = string.format("lighthouse-%s", sanitize(tostring(entry.book_id or "book")))
    end

    return name .. ".epub"
end

--- Encodes a query string for the OPDS endpoint.
-- @tparam table params
-- @treturn string
local function buildQuery(params)
    local parts = {}
    for key, value in pairs(params) do
        parts[#parts + 1] = key .. "=" .. util.urlEncode(tostring(value))
    end
    table.sort(parts)
    return table.concat(parts, "&")
end

-- ---------------------------------------------------------------- visuals --
-- Everything below builds the plugin's single row language. The numbers and
-- strings come from `lighthouse_ui.lua`; this file only turns them into
-- widgets, so the type scale, the gutter and the glyph set cannot drift between
-- Browse, Search, Currently reading and Reading stats.

--- Device scale factor, safe when the screen object is unavailable.
-- @treturn number
local function screenScale()
    local screen = Device and Device.screen
    if type(screen) ~= "table" or type(screen.scaleBySize) ~= "function" then
        return 1
    end
    local ok, value = pcall(screen.scaleBySize, screen, 1)
    if not ok then return 1 end
    local scale = tonumber(value)
    if not scale or scale <= 0 then return 1 end
    return scale
end

--- Screen height in pixels, safe when the screen object is unavailable.
-- @treturn number
local function screenHeight()
    local screen = Device and Device.screen
    if type(screen) ~= "table" or type(screen.getHeight) ~= "function" then
        return 800
    end
    local ok, value = pcall(screen.getHeight, screen)
    if not ok then return 800 end
    local height = tonumber(value)
    if not height or height < 200 then return 800 end
    return height
end

--- Directory holding cached cover thumbnails.
-- @treturn string
local function coverDir()
    return DataStorage:getDataDir() .. "/cache/lighthouse-covers"
end

--- Cached cover path for an entry, or nil when the book has no usable id.
-- @tparam table entry
-- @treturn string|nil
local function coverPath(entry)
    if type(entry) ~= "table" or not entry.book_id then return nil end
    local name = Ui.coverCacheName(entry.book_id)
    if not name then return nil end
    return coverDir() .. "/" .. name
end

--- Negative-cache marker for a book the server has no cover for.
-- @tparam table entry
-- @treturn string|nil
local function coverMissPath(entry)
    if type(entry) ~= "table" or not entry.book_id then return nil end
    local name = Ui.coverMissName(entry.book_id)
    if not name then return nil end
    return coverDir() .. "/" .. name
end

--- True when this row's cover is neither cached nor known to be missing.
-- @tparam table entry
-- @number now unix seconds
-- @treturn boolean
local function coverNeedsFetch(entry, now)
    local path = coverPath(entry)
    if not path then return false end
    if type(entry.thumbnail_href) ~= "string" or entry.thumbnail_href == "" then
        return false
    end
    if Ui.isFresh(lfs.attributes(path, "modification"), now) then return false end
    local miss = coverMissPath(entry)
    if miss and Ui.isFresh(lfs.attributes(miss, "modification"), now) then
        return false
    end
    return true
end

--- KOReader widgets a cover slot needs, loaded once and only if used.
-- Lazy and pcall-guarded: a build that lacks one of these must still open the
-- catalog, just without images, instead of failing at load time.
local coverWidgets
local function loadCoverWidgets()
    if coverWidgets ~= nil then return coverWidgets or nil end
    local ok, loaded = pcall(function()
        return {
            image = require("ui/widget/imagewidget"),
            frame = require("ui/widget/container/framecontainer"),
            center = require("ui/widget/container/centercontainer"),
            text = require("ui/widget/textwidget"),
            font = require("ui/font"),
            geom = require("ui/geometry"),
        }
    end)
    coverWidgets = ok and loaded or false
    if coverWidgets == false then return nil end
    return coverWidgets
end

--- Neutral cover slot: a framed box with a book glyph, never a blank hole.
-- The same slot is used while a cover loads and for a book the server has no
-- cover for, so a coverless book keeps the row's shape instead of breaking the
-- page or drawing an error.
-- @tparam table layout result of `Ui.layout`
-- @treturn table|nil widget
local function coverPlaceholder(layout)
    local widgets = loadCoverWidgets()
    if not widgets then return nil end
    local border = math.max(math.floor(screenScale()), 1)
    local inner = widgets.geom:new{
        w = math.max(layout.cover_width - 2 * border, 1),
        h = math.max(layout.cover_height - 2 * border, 1),
    }
    return widgets.frame:new{
        bordersize = border,
        padding = 0,
        widgets.center:new{
            dimen = inner,
            widgets.text:new{
                text = Ui.GLYPH.cover,
                face = widgets.font:getFace("smallinfofont"),
            },
        },
    }
end

--- Left-gutter marker for a row that is not a book (search, next page).
-- Keeps the gutter aligned instead of leaving an empty notch on those rows.
-- @tparam table layout result of `Ui.layout`
-- @string glyph one of `Ui.GLYPH`
-- @treturn table|nil widget
local function markerSlot(layout, glyph)
    local widgets = loadCoverWidgets()
    if not widgets then return nil end
    return widgets.center:new{
        dimen = widgets.geom:new{ w = layout.cover_width, h = layout.cover_height },
        widgets.text:new{
            text = glyph,
            face = widgets.font:getFace("infofont"),
        },
    }
end

--- Short, human headline for a failed request.
-- Deliberately separate from `describeError`: the headline states what failed in
-- one short line, the detail line says what to do about it. A failure screen
-- shows both instead of a bare "something went wrong".
-- @string err
-- @treturn string
local function errorHeadline(err)
    local code = type(err) == "string" and err or tostring(err or "")
    if code == "not_configured" then
        return _("This plugin is not configured")
    elseif code == "https_unavailable" then
        return _("No HTTPS support in this KOReader build")
    elseif code:match("^network_error") then
        return _("Can't reach the LightHouse server")
    elseif code == "empty_response" then
        return _("The server sent an empty response")
    elseif code == "invalid_response" then
        return _("The server response could not be read")
    elseif code == "html_response" then
        return _("The server sent a web page")
    elseif code:match("^file_error") then
        return _("Can't write the download file")
    elseif code:match("^http_401") or code:match("^http_403") then
        return _("The server rejected this device's key")
    elseif code == "too_many_redirects" or code == "invalid_redirect" then
        return _("The server sent a bad redirect")
    elseif code:match("^http_") then
        return T(_("Server error %1"), code:gsub("^http_", ""))
    end
    return _("The request failed")
end

