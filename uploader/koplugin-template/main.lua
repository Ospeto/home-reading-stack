--- A cached cover for one book id, sized to the row, or nil.
-- The row draws its own placeholder when this returns nil, so a missing or
-- half-written cover costs the picture and never the row.
-- @param cover_id number|string|nil
-- @number width
-- @number height
-- @treturn table|nil widget
function LightHouse:coverWidgetFor(cover_id, width, height)
    local id = Status.num(cover_id)
    if not id then return nil end
    local path = coverPath({ book_id = id })
    if not path or not coverFileWhole(path) then return nil end
    local widgets = loadCoverWidgets()
    if not widgets then return nil end
    return widgets.image:new{
        file = path,
        -- 0 = scale to fit the box, keeping the cover's own aspect.
        scale_factor = 0,
        width = width,
        height = height,
    }
end

--- Fetches the covers of these books, inside the caller's spinner unless silent.
-- A synthetic entry per id is enough: the cover endpoint is keyed by book id, so
-- no OPDS row is needed. Bounded by the same count and wall-clock budget as the
-- catalog prefetch, and every failure stays inside the prefetch.
-- @tparam table ids array of book ids
-- @string[opt] label spinner text
-- @boolean[opt] silent skip creating an inner spinner when already inside one
function LightHouse:prefetchCoverIds(ids, label, silent)
    if not self:coversEnabled() then return end
    local now = os.time()
    local entries = {}
    for id_index = 1, #ids do
        local id = Status.num(ids[id_index])
        if id then
            local entry = {
                book_id = id,
                thumbnail_href = Client.buildUrl(
                    config,
                    string.format("/api/books/%d/cover?w=%d", math.floor(id), Ui.tokens.cover_width_px)
                ),
            }
            if coverNeedsFetch(entry, now) then entries[#entries + 1] = entry end
        end
    end
    if #entries == 0 then return end
    if silent then
        self:prefetchCovers(entries)
        return
    end
    self:withSpinner(label or _("Loading covers…"), function()
        self:prefetchCovers(entries)
        return true
    end)
end

--- ---------------------------------------------------------------------------
-- Navigation: one stack of levels, one rule for going up
-- ---------------------------------------------------------------------------

--- The plugin's navigation stack, top last.
-- `lighthouse_nav.lua` owns the push/replace/pop rules; this is only where the
-- plugin keeps them.
-- @treturn table array of levels
function LightHouse:navStack()
    if type(self.nav) ~= "table" then self.nav = {} end
    return self.nav
end

--- Closes one plugin screen without counting it as going up.
-- Every render calls this on what it replaces: the level stack already says
-- where the reader is going, so the widget's own back must not run.
-- @tparam table|nil widget
function LightHouse:dismissWidget(widget)
    if not widget then return end
    local was_navigating = self.navigating
    self.navigating = true
    pcall(UIManager.close, UIManager, widget)
    self.navigating = was_navigating
end

--- Shows one level of the plugin, remembering how to draw it again.
--
-- The whole model in one function. A level with the same kind and key as the
-- one on the glass replaces it - a page turn, a grouping switch, a refresh, a
-- retry: the reader has not moved. Any other level is one step deeper and is
-- pushed, so Back returns to it with the state it was left in.
-- `render` draws the level and closes whatever it replaces.
-- @tparam table level { kind, key, surface = "page"|"menu", state }
-- @function render draws this level
-- @treturn string|nil "pushed" or "replaced"
function LightHouse:showLevel(level, render)
    if type(level) ~= "table" or type(render) ~= "function" then return nil end
    level.render = render
    local stack = self:navStack()
    local parent = Nav.top(stack)
    -- A detail view of the screen underneath may leave that screen drawn: the
    -- page the reader came from is revealed by closing the menu instead of
    -- being painted again. Only the parent level's own page qualifies.
    level.over_page = parent ~= nil
        and parent.surface == "page"
        and parent.widget ~= nil
        and parent.widget == self.page
    local action = Nav.show(stack, level)
    if action == nil then return nil end
    render()
    return action
end

--- Goes up one level.
-- The header's back mark, the Back key and a menu's own close all end here.
-- Pops the level the reader is on and draws the one below it with the state it
-- was left in; a parent whose page is still on the glass needs no redraw,
-- because revealing it is the whole of going back. Popping the last level
-- leaves the plugin, which is what Back has always done at the top.
function LightHouse:goUp()
    local stack = self:navStack()
    local current = Nav.top(stack)
    -- A menu view is redrawn from its items, so where it was scrolled to has to
    -- be taken down before it is dropped.
    if current and self.menu and type(self.menu.page) == "number" then
        current.state = type(current.state) == "table" and current.state or {}
        current.state.menu_page = self.menu.page
    end
    local previous = Nav.up(stack)
    if not previous then
        self:exitPlugin()
        return
    end
    if previous.widget and previous.widget == self.page then
        UIManager:setDirty(previous.widget, "ui")
        return
    end
    if type(previous.render) == "function" then previous.render() end
end

--- Closes any open overflow sheet or menu.
function LightHouse:closeOverflow()
    if self.overflow_menu then
        self:dismissWidget(self.overflow_menu)
        self.overflow_menu = nil
    end
end

--- Leaves the plugin, the way Back at the top level always has.
function LightHouse:exitPlugin()
    self:closeOverflow()
    self:dismissWidget(self.menu)
    self.menu = nil
    self:dismissWidget(self.page)
    self.page = nil
    -- Nothing of this visit outlives it: a later visit starts at a top level
    -- rather than inheriting a chain the reader has already left.
    self.library_state = nil
    self.view_context = nil
    self._reading_shelf = nil
    self._highlight_groups = nil
    Nav.reset(self:navStack())
end

--- Draws one page model as the plugin's full-screen view.
-- The page replaces any page already on screen. A build that raises is reported
-- as a designed failure screen instead of taking the process with it, because
-- every widget construction here runs inside KOReader's paint path.
-- @tparam table model page model (`lighthouse_views.lua`)
-- @tparam table plan layout plan (`Ui.pagePlan` / `Ui.listPlan`)
-- @tparam table handlers { on_action, on_hold, on_switch, on_overflow }
-- @treturn table|nil the page widget
function LightHouse:showPage(model, plan, handlers)
    handlers = handlers or {}
    self:closeOverflow()
    -- A page is a whole screen, so a menu left over from a level the reader has
    -- left must not stay on the glass behind it. Closing it is not a step up:
    -- the level stack already says where the reader is.
    self:dismissWidget(self.menu)
    self.menu = nil
    if self.page then
        UIManager:close(self.page)
        self.page = nil
    end
    local built_ok, page = pcall(Page.build, {
        model = model,
        plan = plan,
        cover_widget = function(cover_id, width, height)
            return self:coverWidgetFor(cover_id, width, height)
        end,
        -- The reader's cover preference, read once per page: with covers off a
        -- row gives the column back to the text instead of drawing a frame.
        covers = self:coversEnabled(),
        on_action = handlers.on_action,
        on_hold = handlers.on_hold,
        on_switch = handlers.on_switch,
        on_overflow = handlers.on_overflow or function() self:showPageOverflow() end,
        -- Back goes up one level. Before there was a stack this widget could
        -- only close, which is why the header's back mark was an exit.
        on_back = function() self:goUp() end,
        close_callback = function() self.page = nil end,
    })
    if not built_ok or type(page) ~= "table" then
        logger.warn("LightHouse: page build failed:", tostring(page))
        self:showProblem{
            title = _("LightHouse library"),
            headline = _("This screen could not be drawn"),
            detail = _("Open the library again, or download the plugin again from the LightHouse web app."),
            actions = { retryAction(_("Browse library"), function() self:openLibrary{ page = 1 } end) },
        }
        return nil
    end
    self.page = page
    -- The level owns the screen it drew: a menu opened over this page is gone
    -- when the page is, and a step back onto this level needs no redraw while
    -- the widget is still on the glass.
    local level = Nav.top(self:navStack())
    if level then level.widget = page end
    -- The model is kept on the plugin, not only inside the widget: it is what
    -- the screen was asked to draw, and the off-device suite asserts it (a
    -- framebuffer is not available there, and a screenshot is the device's
    -- job).
    self.last_page_model = model
    UIManager:show(page)
    -- The page covers the screen, so the swap has to invalidate the screen. It
    -- cannot leave that to whatever refresh happens to be queued: `UIManager`
    -- `show` and `close` enqueue none of their own (`_refresh` returns early
    -- when it is given no refresh mode), and the fallback that replaces a
    -- missing refresh only runs while the queue is empty. The spinner this
    -- view shows while it fetches leaves a deferred refresh behind that reports
    -- its own box - a band across the middle of the screen - so a page turn
    -- could be flushed over that band alone, leaving the rest of the glass
    -- showing the page just left. Ask for the page's own box explicitly; the
    -- queued band then merges into it instead of standing in for it.
    UIManager:setDirty(page, "ui")
    return page
end

--- The overflow sheet behind the header's ⋮.
-- Offers unified in-app navigation across Library / Reading / Highlights / Stats
-- plus refresh, sort/filter, jump, covers toggle and connection details.
function LightHouse:showPageOverflow()
    self:closeOverflow()
    local state = self.library_state
    local ctx = self.view_context or {}
    local view_kind = state and "library" or Status.str(ctx.kind, "stats")
    local rows = {}
    local menu_items = {}

    local function addAction(row_table, label_text, fn, bold)
        local wrapped = function()
            self:closeOverflow()
            fn()
        end
        row_table[#row_table + 1] = { text = label_text, callback = wrapped }
        menu_items[#menu_items + 1] = { text = label_text, bold = bold == true, callback = wrapped }
    end

    -- Unified in-app navigation across the plugin's screens.
    local nav_row = {}
    if view_kind ~= "library" then
        addAction(nav_row, _("Library"), function()
            self:openLibrary{ mode = "books", page = 1, query = "", title = "", series_name = "" }
        end)
    end
    if view_kind ~= "reading" then
        addAction(nav_row, _("Currently reading"), function() self:showReading() end)
    end
    if view_kind ~= "highlights" or ctx.record ~= nil then
        addAction(nav_row, _("Highlights"), function() self:showHighlights() end)
    end
    if view_kind ~= "stats" then
        addAction(nav_row, _("Reading stats"), function() self:showStats() end)
    end
    if view_kind ~= "storage" then
        addAction(nav_row, _("Device storage"), function() self:showStorage() end)
    end
    if #nav_row > 0 then rows[#rows + 1] = nav_row end

    -- Current-screen actions.
    local action_row = {}
    if state then
        addAction(action_row, _("Refresh"), function()
            self:openLibrary{ page = state.page, refresh = true }
        end, true)
        addAction(action_row, _("Search"), function() self:showSearchDialog() end)
        if state.mode == "books" then
            addAction(action_row, _("Sort & Filter"), function() self:showSortFilterDialog() end)
        else
            local grouping = self._groupings and self._groupings[state.mode == "series" and "series" or "authors"]
            if grouping and grouping.groups then
                local plan = self:libraryPlan(state.query == "")
                local page_size = math.max(math.min(plan.rows, pageSize()), 1)
                addAction(action_row, _("Jump A–Z"), function()
                    self:showLetterJumpDialog(grouping.groups, page_size)
                end)
            end
        end
    else
        addAction(action_row, _("Refresh"), function()
            if view_kind == "reading" then
                self:showReading{ page = ctx.page or 1, refresh = true }
            elseif view_kind == "highlights" then
                self:showHighlights(ctx.record, { page = ctx.page or 1, refresh = true })
            elseif view_kind == "storage" then
                self:showStorage{ page = ctx.page or 1, refresh = true }
            elseif view_kind == "book" and ctx.entry then
                self:openBookDetails(ctx.entry)
            else
