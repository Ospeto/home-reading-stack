#!/usr/bin/env bun
/**
 * scripts/refresh-discover-seeds.ts
 *
 * Refreshes the curated "New Releases" list for the Discover tab.
 *
 * The New Releases tab is curated on purpose: a card only appears when a real download source
 * (Lnori or Elsci.one) carries the title, so the tab never advertises a book nobody can download.
 * The problem this script solves is that the curated list used to be compiled into
 * `uploader/discover.ts` and froze at 2020-2023 titles, so a tab called "New Releases" showed
 * books that were years old.
 *
 * Run on a schedule (see the `reading-discover-seeds` LaunchAgent generated by
 * `bin/lighthouse install-daemons`), it:
 *   1. asks AniList for recently started light novels,
 *   2. keeps only the titles that pass the real-source gate,
 *   3. drops anything already in Trending (the two tabs are contractually disjoint), and
 *   4. writes `data/discover-new-releases.json` atomically for the reader in
 *      `uploader/discover-seeds.ts`.
 *
 * This script never edits source code and never invents a date: a title with no start date keeps
 * a null release date so it cannot be presented as new.
 */

import path from "node:path";
import process from "node:process";
import {
  fetchOnlineFeedForRefresh,
  deduplicateDiscoverNovels,
  normalizeTitleForMatch,
  canonicalTitleKey,
  SEED_TRENDING_NOVELS,
  fetchDiscoverFeed,
} from "../uploader/discover";
import {
  getDefaultSeedStorePath,
  writeCuratedNewReleaseSeeds,
} from "../uploader/discover-seeds";

export interface RefreshResult {
  writtenCount: number;
  storePath: string;
  generatedAt: string;
  skippedTrending: number;
  cycles: unknown[];
}

export async function refreshDiscoverSeeds(options?: {
  storePath?: string;
  now?: Date;
  limit?: number;
  log?: (message: string) => void;
}): Promise<RefreshResult> {
  const log = options?.log ?? ((message: string) => console.log(message));
  const now = options?.now ?? new Date();
  const limit = Math.max(1, Math.min(40, options?.limit ?? 20));

  log("[DiscoverSeeds] Fetching recently released light novels from AniList…");

  // `skipSeedSupplement` keeps this refresh from reading back the very list it replaces.
  const fresh = await fetchOnlineFeedForRefresh("new", 15000, {
    skipSeedSupplement: true,
  });

  if (!fresh || fresh.length === 0) {
    throw new Error(
      "AniList returned no downloadable new releases; keeping the existing curated list",
    );
  }
  log(`[DiscoverSeeds] AniList returned ${fresh.length} downloadable candidates.`);

  // Trending and New Releases must stay disjoint, or a title shows up twice in the UI.
  let trendingKeys = new Set<string>();
  try {
    const trending = await fetchDiscoverFeed("trending", {
      skipCrossCheck: true,
      skipSeedSupplement: true,
    });
    trendingKeys = collectTitleKeys(trending);
  } catch (err: any) {
    log(`[DiscoverSeeds] Could not read the trending feed, using compiled seeds: ${err?.message || err}`);
    trendingKeys = collectTitleKeys(SEED_TRENDING_NOVELS);
  }

  const kept = [];
  let skippedTrending = 0;
  for (const novel of fresh) {
    if (titleKeys(novel).some((key) => trendingKeys.has(key))) {
      skippedTrending += 1;
      continue;
    }
    kept.push(novel);
    if (kept.length >= limit) break;
  }

  const deduped = deduplicateDiscoverNovels(kept);
  if (deduped.length === 0) {
    throw new Error(
      "Every candidate was already in Trending; keeping the existing curated list",
    );
  }

  const generatedAt = now.toISOString();
  const storePath = writeCuratedNewReleaseSeeds(deduped, {
    storePath: options?.storePath ?? getDefaultSeedStorePath(),
    generatedAt,
  });

  log(
    `[DiscoverSeeds] Wrote ${deduped.length} curated releases to ${storePath} ` +
      `(skipped ${skippedTrending} already trending).`,
  );

  return {
    writtenCount: deduped.length,
    storePath,
    generatedAt,
    skippedTrending,
    cycles: [],
  };
}

function titleKeys(novel: { title: string; titleRomaji?: string }): string[] {
  const keys = [normalizeTitleForMatch(novel.title), canonicalTitleKey(novel.title)];
  if (novel.titleRomaji) {
    keys.push(normalizeTitleForMatch(novel.titleRomaji), canonicalTitleKey(novel.titleRomaji));
  }
  return keys.filter(Boolean);
}

function collectTitleKeys(novels: Array<{ title: string; titleRomaji?: string }>): Set<string> {
  const keys = new Set<string>();
  for (const novel of novels) {
    for (const key of titleKeys(novel)) keys.add(key);
  }
  return keys;
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const dryRun = args.includes("--dry-run");
  const storeArgIndex = args.indexOf("--store");
  const storePath =
    storeArgIndex >= 0 && args[storeArgIndex + 1]
      ? path.resolve(args[storeArgIndex + 1])
      : undefined;

  try {
    if (dryRun) {
      const fresh = await fetchOnlineFeedForRefresh("new", 15000, {
        skipSeedSupplement: true,
      });
      const count = fresh?.length ?? 0;
      console.log(`[DiscoverSeeds] Dry run: ${count} downloadable candidates would be written.`);
      for (const novel of (fresh ?? []).slice(0, 25)) {
        console.log(
          `  - ${novel.title} (${novel.releaseDate ?? "no release date"}) ` +
            `[${novel.source}]`,
        );
      }
      return;
    }

    await refreshDiscoverSeeds({ storePath });
  } catch (err: any) {
    console.error(`[DiscoverSeeds] Refresh failed: ${err?.message || err}`);
    process.exit(1);
  }
}

if ((import.meta as any).main) {
  await main();
}
